// Package deploy carries spoor's deployment content inside the binary, so
// `spoor export` can write the Fluent Bit, Fleet and Kubernetes files that
// match the binary an operator actually runs, with the host's own paths.
//
// Every directory under deploy/ is embedded as it exists at build time
// (fleet/, fluent-bit/ and, once it is added, kubernetes/). The pattern
// embeds whole subdirectories but no file that sits directly in deploy/,
// so this Go file is not part of the content. Files whose names start with
// "." or "_" are left out, as go:embed does for directory patterns.
//
// The Fleet library under fleet/lib is generated by internal/fleetgen; the
// exporter regenerates it with the host's paths instead of copying the
// committed bytes. Test evidence (VERIFIED.md, verify.sh) is embedded with
// the rest and filtered by the exporter.
package deploy

import (
	"embed"
	"io/fs"
)

//go:embed */*
var content embed.FS

// FS returns the embedded tree. Paths are slash separated and relative to
// deploy/, for example "fluent-bit/spoor.yaml".
func FS() fs.FS { return content }

// Sub returns the subtree of one content set ("fleet", "fluent-bit",
// "kubernetes"). ok is false when this build carries no such directory.
func Sub(name string) (sub fs.FS, ok bool) {
	if !fs.ValidPath(name) || name == "." {
		return nil, false
	}
	fi, err := fs.Stat(content, name)
	if err != nil || !fi.IsDir() {
		return nil, false
	}
	sub, err = fs.Sub(content, name)
	if err != nil {
		return nil, false
	}
	return sub, true
}

// Sets lists the content sets this build carries, in name order.
func Sets() []string {
	ents, err := fs.ReadDir(content, ".")
	if err != nil {
		return nil
	}
	var out []string
	for _, e := range ents {
		if e.IsDir() {
			out = append(out, e.Name())
		}
	}
	return out
}
