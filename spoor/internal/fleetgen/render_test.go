// Keys Fleet's GitOps format accepts for each object, as used here
// (docs/Configuration/yaml-files.md; the files pass `fleetctl gitops
// --dry-run` against Fleet 4.94.1, see deploy/fleet/VERIFIED.md).
var gitopsKeys = map[string][]string{
	"labels":   {"name", "description", "query", "label_membership_type", "platform"},
	"policies": {"name", "description", "resolution", "query", "platform", "critical"},
	"reports":  {"name", "description", "query", "interval", "platform", "logging", "automations_enabled", "discard_data", "observer_can_run"},
}

func TestGenerateDeterministic(t *testing.T) {
	a, err := Generate(Options{})
	if err != nil {
		t.Fatal(err)
	}
	b, err := Generate(Options{})
	if err != nil {
		t.Fatal(err)
	}
	if len(a) != len(b) {
		t.Fatal("file sets differ")
	}
	for k := range a {
		if !bytes.Equal(a[k], b[k]) {
			t.Errorf("%s differs between two runs", k)
		}
	}
	want := []string{FileATC, FileATCExample, FileBaseExample, FileContent, FileOptIn}
	for _, p := range []string{ProfileStock, ProfileFleetd, ProfileBuiltin} {
		for _, k := range []string{"labels", "policies", "reports"} {
			want = append(want, ProfileFile(p, k))
		}
	}
	for _, w := range want {
		if a[w] == nil {
			t.Errorf("Generate produced no %s", w)
		}
	}
	if len(a) != len(want) {
		t.Errorf("Generate produced %d files, want %d", len(a), len(want))
	}
}

// knownTables are the tables generated SQL may read.
func knownTables() map[string]bool {
	m := map[string]bool{}
	for _, td := range state.Tables {
		m[td.OsqueryName()] = true
	}
	for name := range osqueryStubs {
		m[name] = true
	}
	return m
}

var fromRe = regexp.MustCompile(`(?i)\b(?:FROM|JOIN)\s+([a-z_][a-z0-9_]*)`)

func TestGeneratedYAML(t *testing.T) {
	files, err := Generate(Options{})
	if err != nil {
		t.Fatal(err)
	}
	tables := knownTables()
	names := map[string]map[string]string{} // profile -> name -> kind
	var keys []string
	for k := range files {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, path := range keys {
		b := files[path]
		if !strings.HasSuffix(path, ".yml") {
			continue
		}
		if !bytes.HasPrefix(b, []byte("# spoor Fleet content: ")) || !bytes.Contains(b, []byte("GENERATED by internal/fleetgen")) {
			t.Errorf("%s: missing generated-file header", path)
		}
		for i, line := range strings.Split(string(b), "\n") {
			if strings.TrimRight(line, " \t") != line || strings.Contains(line, "\t") {
				t.Errorf("%s:%d: trailing whitespace or tab", path, i+1)
			}
		}
		dec := yaml.NewDecoder(bytes.NewReader(b))
		var doc any
		if err := dec.Decode(&doc); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		if err := dec.Decode(new(any)); err != io.EOF {
			t.Errorf("%s: more than one YAML document", path)
		}
		kind := strings.TrimSuffix(path[strings.LastIndex(path, "/")+1:], ".yml")
		kind = strings.TrimPrefix(kind, "exec-events.")
		allowed, isList := gitopsKeys[kind]
		if !isList {
			continue // agent options
		}
		prof := path[:strings.Index(path, "/")]
		if names[prof] == nil {
			names[prof] = map[string]string{}
		}
		items, ok := doc.([]any)
		if !ok || len(items) == 0 {
			t.Fatalf("%s: not a non-empty list", path)
		}
		for _, it := range items {
			m := it.(map[string]any)
			for k := range m {
				if !contains(allowed, k) {
					t.Errorf("%s: key %q is not a %s key", path, k, kind)
				}
			}
			name, _ := m["name"].(string)
			q, _ := m["query"].(string)
			if name == "" || q == "" || m["description"] == "" {
				t.Errorf("%s: entry without name, query or description: %v", path, m)
			}
			if prev, dup := names[prof][name]; dup {
				t.Errorf("%s: name %q also used by a %s", path, name, prev)
			}
			names[prof][name] = kind
			if !strings.HasSuffix(strings.TrimSpace(q), ";") {
				t.Errorf("%s/%s: query does not end with ';'", path, name)
			}
			for _, mt := range fromRe.FindAllStringSubmatch(q, -1) {
				tbl := strings.ToLower(mt[1])
				if !tables[tbl] && !cteName(q, tbl) {
					t.Errorf("%s/%s: reads unknown table %q", path, name, tbl)
				}
			}
			if kind == "policies" && m["platform"] != fleetPlatforms {
				t.Errorf("%s/%s: platform %v", path, name, m["platform"])
			}
			if kind == "reports" {
				if iv, _ := m["interval"].(int); iv < 300 {
					t.Errorf("%s/%s: interval %v", path, name, m["interval"])
				}
				switch m["logging"] {
				case loggingSnapshot, loggingDifferentialNoRem:
				default:
					t.Errorf("%s/%s: logging %v", path, name, m["logging"])
				}
			}
		}
	}
	// The opt-in file opens with the privacy warning.
	if !bytes.Contains(files[FileOptIn], []byte("# PRIVACY WARNING - OPT-IN EXAMPLE ONLY.")) {
		t.Error("opt-in file lacks the privacy warning")
	}
	if !bytes.Contains(files[FileATC], []byte("# THIS IS A FRAGMENT.")) {
		t.Error("ATC fragment lacks the merge warning")
	}
	md := string(files[FileContent])
	c := mustBuild(t, Options{})
	for _, p := range c.Profiles {
		for _, pol := range p.Policies {
			if !strings.Contains(md, pol.Name) {
				t.Errorf("CONTENT.md does not list %q", pol.Name)
			}
		}
	}
}

func cteName(q, name string) bool {
	return regexp.MustCompile(`(?i)\b`+regexp.QuoteMeta(name)+`\s+AS\s+MATERIALIZED`).MatchString(q) ||
		regexp.MustCompile(`(?i)\b(?:FROM|JOIN)\s+`+regexp.QuoteMeta(name)+`\s+[a-z]\b`).MatchString(q) &&
			strings.Contains(strings.ToLower(q), "with ")
}

func contains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}

func TestApplySpecs(t *testing.T) {
	c := mustBuild(t, Options{})
	p := mustProfile(t, c, ProfileStock)
	b, err := ApplySpecs(p, "spoor-c5-")
	if err != nil {
		t.Fatal(err)
	}
	dec := yaml.NewDecoder(bytes.NewReader(b))
	counts := map[string]int{}
	for {
		var doc struct {
			APIVersion string         `yaml:"apiVersion"`
			Kind       string         `yaml:"kind"`
			Spec       map[string]any `yaml:"spec"`
		}
		err := dec.Decode(&doc)
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		if doc.APIVersion != "v1" {
			t.Errorf("apiVersion %q", doc.APIVersion)
		}
		counts[doc.Kind]++
		if n, _ := doc.Spec["name"].(string); !strings.HasPrefix(n, "spoor-c5-") {
			t.Errorf("%s %q not prefixed", doc.Kind, n)
		}
	}
	if counts["label"] != len(p.Labels) || counts["policy"] != len(p.Policies) || counts["report"] != len(p.Reports) {
		t.Errorf("documents %v", counts)
	}
	for _, bad := range []string{"", "x", "spoor\nc5", "spoor-c5-é", "a;b", strings.Repeat("a", 41)} {
		if _, err := ApplySpecs(p, bad); err == nil {
			t.Errorf("prefix %q accepted", bad)
		}
	}
}

func TestHumanWindows(t *testing.T) {
	for d, want := range map[string]string{
		"30m": "30 minutes", "24h": "24 hours", "1h": "1 hour", "168h": "7 days", "90s": "90 seconds", "48h": "2 days",
	} {
		dur, _ := parseDur(d)
		if got := human(dur); got != want {
			t.Errorf("human(%s) = %q, want %q", d, got, want)
		}
	}
}

func parseDur(s string) (d time.Duration, err error) { return time.ParseDuration(s) }

// TestFleetFieldLimits: Fleet refuses a label whose description exceeds 255
// characters ("description may not exceed 255 characters", fleetctl 4.94.1
// gitops dry run), and names are VARCHAR(255) columns.
func TestFleetFieldLimits(t *testing.T) {
	c := mustBuild(t, Options{})
	check := func(what, name, desc string, descLimit bool) {
		if n := utf8.RuneCountInString(name); n > 255 {
			t.Errorf("%s %q: name has %d characters, Fleet allows 255", what, name, n)
		}
		if n := utf8.RuneCountInString(desc); descLimit && n > 255 {
			t.Errorf("%s %q: description has %d characters, Fleet allows 255", what, name, n)
		}
	}
	for _, p := range c.Profiles {
		for _, l := range p.Labels {
			check("label", l.Name, l.Description, true)
		}
		for _, q := range p.Policies {
			check("policy", q.Name, q.Description, false)
		}
		for _, r := range p.Reports {
			check("report", r.Name, r.Description, false)
		}
	}
	for _, l := range readPremiumExample(t).Labels {
		name, _ := l["name"].(string)
		desc, _ := l["description"].(string)
		check("example label", name, desc, true)
	}
}
