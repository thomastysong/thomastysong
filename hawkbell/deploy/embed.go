// Package deploy carries hawkbell's deployment content inside the binary, so
// `hawkbell export` can write the Fluent Bit, Fleet and Kubernetes files that
// match the binary an operator actually runs, with the host's own paths.
//
// The content sets are fleet/, fluent-bit/ and kubernetes/. The embed
// patterns below name their files and subdirectories one by one, so that
// the records of how the content was verified (VERIFIED.md, verify.sh) are
// not compiled into the binary; TestEmbedsAllContent fails when a file is
// added under deploy/ and not here. Inside an embedded subdirectory, files
// whose names start with "." or "_" are left out, as go:embed does for
// directory patterns.
//
// The Fleet library under fleet/lib is generated by internal/fleetgen; the
// exporter regenerates it with the host's paths instead of copying the
// committed bytes.
package deploy

import (
	"embed"
	"io/fs"
)

//go:embed fleet/README.md fleet/gitops fleet/lib fleet/scripts fleet/software
//go:embed fluent-bit/*.yaml fluent-bit/no-binary fluent-bit/outputs
//go:embed kubernetes/.gitattributes kubernetes/README.md kubernetes/*.yaml kubernetes/in-image kubernetes/seccomp
var content embed.FS

// notContent are the files under deploy/ that are not embedded: records
// and scripts of the verification of the content.
var notContent = []string{"fleet/VERIFIED.md", "fleet/verify.sh", "fluent-bit/VERIFIED.md", "kubernetes/VERIFIED.md"}

// FS returns the embedded tree. Paths are slash separated and relative to
// deploy/, for example "fluent-bit/hawkbell.yaml".
func FS() fs.FS { return content }

// Sub returns the subtree of one content set ("fleet", "fluent-bit",
// "kubernetes"). ok is false when this build carries no such directory.
func Sub(name string) (sub fs.FS, ok bool) {
	if !fs.ValidPath(name) || name == "." {
		return nil, false
	}
	fi, err := fs.Stat(content, name)
	if err != nil || !fi.IsDir() {
		return nil, false
	}
	sub, err = fs.Sub(content, name)
	if err != nil {
		return nil, false
	}
	return sub, true
}

// Sets lists the content sets this build carries, in name order.
func Sets() []string {
	ents, err := fs.ReadDir(content, ".")
	if err != nil {
		return nil
	}
	var out []string
	for _, e := range ents {
		if e.IsDir() {
			out = append(out, e.Name())
		}
	}
	return out
}
