func TestClaudeSession(t *testing.T) {
	p, ok := ForFormat(FormatClaude)
	if !ok {
		t.Fatal("no claude parser")
	}
	evs, st := parseLines(t, p, claudeMainPath, claudeMain...)
	wantSeq(t, evs,
		"prompt.submit",
		"tool.pre Read",
		"tool.pre Bash",
		"tool.post Read ok",
		"tool.post Bash error",
		"tool.pre Bash",
		"tool.post Bash denied deny",
		"tool.pre mcp__github__create_issue",
		"tool.post mcp__github__create_issue error",
		"tool.pre Agent",
		"tool.post Agent ok",
		"config.change",
		"tool.pre WebFetch",
		"tool.pre Write",
		"context.compact",
		"turn.end interrupted",
	)
	checkCommon(t, evs, "claude-code", claudeMainPath)

	if st.SessionID != "5d1f26db" || st.CWD != "/work/repo" || st.Version != "2.1.300" || st.Model != "claude-opus-5" {
		t.Errorf("state = %+v", st)
	}
	if st.PermissionMode != "bypass" {
		t.Errorf("permission mode = %q", st.PermissionMode)
	}
	if st.Unknown != 1 || st.Malformed != 0 || st.Lines != uint64(len(claudeMain)) {
		t.Errorf("unknown=%d malformed=%d lines=%d", st.Unknown, st.Malformed, st.Lines)
	}
	if len(st.Pending) != 2 { // WebFetch and Write never got results
		t.Errorf("pending = %d", len(st.Pending))
	}

	prompt := evs[0]
	if prompt.Content == nil || !strings.Contains(prompt.Content.PromptText, "fix the build") || prompt.Prompt.Len != len(prompt.Content.PromptText) {
		t.Errorf("prompt = %+v %+v", prompt.Prompt, prompt.Content)
	}
	if prompt.Session.PermissionMode != "default" || prompt.Session.ID != "5d1f26db" || prompt.Agent.Version != "2.1.300" {
		t.Errorf("prompt session = %+v", prompt.Session)
	}
	if got := prompt.TS.String(); got != "2026-11-01T13:27:10.000000Z" {
		t.Errorf("timestamp = %s", got)
	}

	read := find(t, evs, event.TypeToolPre, "toolu_01")
	if read.Tool.Kind != event.ToolFileRead || read.Target == nil || read.Target.Path != "/work/repo/Makefile" {
		t.Errorf("read = %+v %+v", read.Tool, read.Target)
	}
	if read.Content.ToolInput["file_path"] != "/work/repo/Makefile" || read.Tool.InputSHA256 == "" || len(read.Tool.InputKeys) != 1 {
		t.Errorf("read input = %+v %+v", read.Content, read.Tool)
	}
	if read.Session.Model != "claude-opus-5" {
		t.Errorf("model = %q", read.Session.Model)
	}

	bashPost := find(t, evs, event.TypeToolPost, "toolu_02")
	if bashPost.Tool.Kind != event.ToolShell || bashPost.Outcome.ExitCode == nil || *bashPost.Outcome.ExitCode != 2 || bashPost.Outcome.Error != "exit_code" {
		t.Errorf("bash post = %+v %+v", bashPost.Tool, bashPost.Outcome)
	}
	if bashPost.Content.ToolOutput != "Exit code 2\nboom" || bashPost.Tool.OutputLen != 16 || bashPost.Tool.OutputSHA256 != "" {
		t.Errorf("bash output = %+v %+v", bashPost.Content, bashPost.Tool)
	}
	if bashPost.Target == nil || bashPost.Target.Command != "make build\necho done" || bashPost.Content.ToolInput["command"] == nil {
		t.Errorf("post must carry the call's target and input: %+v", bashPost.Target)
	}
	if bashPost.Tool.InputSHA256 != find(t, evs, event.TypeToolPre, "toolu_02").Tool.InputSHA256 {
		t.Error("pre and post must share the input hash")
	}

	denied := find(t, evs, event.TypeToolPost, "toolu_03")
	if denied.Outcome.DecisionSource != "user" || denied.Outcome.Error != "user_rejected" {
		t.Errorf("denied = %+v", denied.Outcome)
	}

	mcp := find(t, evs, event.TypeToolPre, "toolu_04")
	if mcp.Tool.Kind != event.ToolMCP || mcp.Tool.MCPServer != "github" || mcp.Tool.MCPTool != "create_issue" {
		t.Errorf("mcp = %+v", mcp.Tool)
	}
	// An MCP server's own error text never counts as a user refusal.
	if o := find(t, evs, event.TypeToolPost, "toolu_04").Outcome; o.Status != "error" || o.Decision != "" {
		t.Errorf("mcp outcome = %+v", o)
	}

	agent := find(t, evs, event.TypeToolPre, "toolu_05")
	if agent.Tool.Kind != event.ToolSubagent || agent.Labels["subagent_type"] != "Explore" || agent.Target != nil {
		t.Errorf("agent = %+v labels=%v target=%+v", agent.Tool, agent.Labels, agent.Target)
	}

	cfg := find(t, evs, event.TypeConfigChange, "")
	if cfg.Labels["change"] != "permission_mode" || cfg.Labels["from"] != "default" || cfg.Labels["to"] != "bypass" || cfg.Session.PermissionMode != "bypass" {
		t.Errorf("config change = %v %+v", cfg.Labels, cfg.Session)
	}

	fetch := find(t, evs, event.TypeToolPre, "toolu_06")
	if fetch.Tool.Kind != event.ToolWebFetch || fetch.Target.Host != "paste.example" || strings.Contains(fetch.Target.URL, "hunter2") {
		t.Errorf("fetch = %+v", fetch.Target)
	}
	write := find(t, evs, event.TypeToolPre, "toolu_07")
	if write.Tool.Kind != event.ToolFileWrite || write.Content.FileContent != "API_KEY=abc123" || write.Target.Path != "/work/repo/.env" {
		t.Errorf("write = %+v %+v", write.Content, write.Target)
	}
	if c := find(t, evs, event.TypeCompact, ""); c.Labels["trigger"] != "auto" {
		t.Errorf("compact labels = %v", c.Labels)
	}

	// Content is local-only: nothing a prompt, an input value, an output or
	// a URL credential says may appear on the wire.
	out := wire(t, evs)
	for _, secret := range []string{"sk-ant-SECRETSECRET", "fix the build", "hunter2", "API_KEY=abc123", "boom", "all: build", "found 3 files", "explore src"} {
		if strings.Contains(out, secret) {
			t.Errorf("wire output leaks %q", secret)
		}
	}

	// Re-parsing the same lines gives the same ids (at-least-once dedupe).
	again, _ := parseLines(t, p, "/some/other/place/projects/x/5d1f26db.jsonl", claudeMain...)
	if !sameIDs(evs, again) {
		t.Error("event ids are not deterministic")
	}
}

