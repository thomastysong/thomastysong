func TestClaudeOutcomeTable(t *testing.T) {
	cases := []struct {
		kind    string
		isError bool
		text    string
		mcp     bool
		status  string
		source  string
	}{
		{"", false, "fine", false, "ok", ""},
		{"user-rejected", true, "x", false, "denied", "user"},
		{"permission-rule", true, "x", false, "denied", "policy"},
		{"automode-classifier", true, "x", false, "denied", "policy"},
		{"interrupted", true, "Interrupted", false, "interrupted", ""},
		{"cancelled", true, "x", false, "interrupted", ""},
		{"", true, "The user doesn't want to take this action right now.", false, "denied", "user"},
		{"", true, "Permission to use Bash has been denied.", false, "denied", "policy"},
		{"", true, "Hook PreToolUse:Bash denied this tool", false, "denied", "hook"},
		{"", true, "Blocked by hook", false, "denied", "hook"},
		{"", true, "PreToolUse:Bash hook error: exit 1", false, "error", ""},
		{"", true, "[Request interrupted by user for tool use]", false, "interrupted", ""},
		{"", true, "<tool_use_error>File not found</tool_use_error>", false, "error", ""},
		{"", true, "Permission to use tool denied", true, "error", ""},
		{"some-future-kind", true, "The user doesn't want to proceed", false, "error", ""},
	}
	for _, c := range cases {
		o := claudeOutcome(c.kind, c.isError, c.text, c.mcp)
		if o.Status != c.status || o.DecisionSource != c.source {
			t.Errorf("claudeOutcome(%q,%v,%q,%v) = %+v; want %s/%s", c.kind, c.isError, c.text, c.mcp, o, c.status, c.source)
		}
		if o.Error == c.text && c.text != "" {
			t.Errorf("outcome error must be a code, not tool text: %q", o.Error)
		}
	}
}

