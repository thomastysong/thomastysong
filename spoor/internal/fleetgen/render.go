// File names inside deploy/fleet/lib.
const (
	FileATC        = "agent-options.atc.yml"
	FileATCExample = "agent-options.example.yml"
	// FileBaseExample is the same typical base without spoor's ATC tables:
	// the agent options of tier 3 (the spoor extension), which must not
	// carry them.
	FileBaseExample = "agent-options.base.example.yml"
	FileContent     = "CONTENT.md"
	FileOptIn       = "opt-in/exec-events.reports.yml"
	fileLabels      = "labels.yml"
	filePolicies    = "policies.yml"
	fileReports     = "reports.yml"
)

// ProfileFile returns the path of one of a profile's files ("labels",
// "policies" or "reports") relative to deploy/fleet/lib.
func ProfileFile(profile, kind string) string { return profile + "/" + kind + ".yml" }

// Generate returns the content of deploy/fleet/lib: a map from slash-
// separated path relative to that directory to file bytes. The zero Options
// give exactly the committed files; `spoor export fleet` passes this host's
// paths.
func Generate(o Options) (files map[string][]byte, err error) {
	defer func() {
		if r := recover(); r != nil {
			files, err = nil, fmt.Errorf("fleetgen: internal error: %v", r)
		}
	}()
	c, err := Build(o)
	if err != nil {
		return nil, err
	}
	return c.Render()
}

// Render renders built content into files.
func (c *Content) Render() (files map[string][]byte, err error) {
	defer func() {
		if r := recover(); r != nil {
			files, err = nil, fmt.Errorf("fleetgen: internal error: %v", r)
		}
	}()
	if c == nil || len(c.ATC) == 0 {
		return nil, errors.New("fleetgen: no content (use Build)")
	}
	files = map[string][]byte{}
	put := func(name string, b []byte, err error) error {
		if err != nil {
			return fmt.Errorf("fleetgen: render %s: %w", name, err)
		}
		files[name] = b
		return nil
	}
	atc, err := c.renderATCFragment()
	if err := put(FileATC, atc, err); err != nil {
		return nil, err
	}
	ex, err := c.renderATCExample()
	if err := put(FileATCExample, ex, err); err != nil {
		return nil, err
	}
	base, err := c.renderBaseExample()
	if err := put(FileBaseExample, base, err); err != nil {
		return nil, err
	}
	for _, p := range c.Profiles {
		hdr := c.header(p.Title+" ("+p.Name+" profile).", p.Summary)
		b, err := encodeDoc(hdr, labelsNode(p.Labels))
		if err := put(ProfileFile(p.Name, "labels"), b, err); err != nil {
			return nil, err
		}
		b, err = encodeDoc(hdr, policiesNode(p.Policies))
		if err := put(ProfileFile(p.Name, "policies"), b, err); err != nil {
			return nil, err
		}
		b, err = encodeDoc(hdr, reportsNode(p.Reports))
		if err := put(ProfileFile(p.Name, "reports"), b, err); err != nil {
			return nil, err
		}
	}
	b, err := encodeDoc(c.header("Opt-in exec-event reports.", "")+"#\n"+optInHeader(), reportsNode(c.OptIn))
	if err := put(FileOptIn, b, err); err != nil {
		return nil, err
	}
	if err := put(FileContent, c.renderMarkdown(), nil); err != nil {
		return nil, err
	}
	return files, nil
}

// header is the comment block every generated YAML file starts with.
func (c *Content) header(title, summary string) string {
	var b strings.Builder
	line := func(s string) {
		if s == "" {
			b.WriteString("#\n")
			return
		}
		b.WriteString("# " + s + "\n")
	}
	line("spoor Fleet content: " + title)
	if summary != "" {
		for _, l := range wrap(summary, 76) {
			line(l)
		}
	}
	line("")
	line("GENERATED by internal/fleetgen from the state table definitions and")
	line("catalog " + c.CatalogVersion + ". Do not edit: regenerate with")
	line("  go test ./internal/fleetgen -run TestGolden -update")
	line("or write a copy for your hosts' paths with `spoor export fleet`.")
	line("Heartbeat windows: sensor policy " + human(c.AlertWindow) + ", every other spoor policy " +
		human(c.GuardWindow) + ".")
	return b.String()
}

// wrap splits text into lines of at most width bytes at spaces.
func wrap(s string, width int) []string {
	var out []string
	var cur string
	for _, w := range strings.Fields(s) {
		if cur != "" && len(cur)+1+len(w) > width {
			out = append(out, cur)
			cur = w
			continue
		}
		if cur == "" {
			cur = w
		} else {
			cur += " " + w
		}
	}
	if cur != "" {
		out = append(out, cur)
	}
	return out
}

// ---- YAML nodes ----

func scalar(v string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
	return n
}

func sqlScalar(v string) *yaml.Node {
	n := scalar(v)
	n.Style = yaml.LiteralStyle
	return n
}

func intScalar(i int) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.Itoa(i)}
}

func boolScalar(b bool) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: strconv.FormatBool(b)}
}

// mapping builds a mapping from key/value pairs, in order.
func mapping(kv ...any) *yaml.Node {
	n := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	for i := 0; i+1 < len(kv); i += 2 {
		n.Content = append(n.Content, scalar(kv[i].(string)), kv[i+1].(*yaml.Node))
	}
	return n
}

func sequence(items ...*yaml.Node) *yaml.Node {
	return &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: items}
}

func labelsNode(ls []Label) *yaml.Node {
	out := sequence()
	for _, l := range ls {
		m := mapping("name", scalar(l.Name), "description", scalar(l.Description),
			"query", sqlScalar(l.Query), "label_membership_type", scalar("dynamic"))
		if l.Platform != "" {
			m.Content = append(m.Content, scalar("platform"), scalar(l.Platform))
		}
		out.Content = append(out.Content, m)
	}
	return out
}

func policyNode(p Policy) *yaml.Node {
	return mapping("name", scalar(p.Name), "description", scalar(p.Description),
		"resolution", scalar(p.Resolution), "query", sqlScalar(p.Query),
		"platform", scalar(p.Platform), "critical", boolScalar(false))
}

func policiesNode(ps []Policy) *yaml.Node {
	out := sequence()
	for _, p := range ps {
		out.Content = append(out.Content, policyNode(p))
	}
	return out
}

func reportNode(r Report) *yaml.Node {
	return mapping("name", scalar(r.Name), "description", scalar(r.Description),
		"query", sqlScalar(r.Query), "interval", intScalar(r.Interval),
		"platform", scalar(r.Platform), "logging", scalar(r.Logging),
		"automations_enabled", boolScalar(r.AutomationsEnabled),
		"discard_data", boolScalar(r.DiscardData), "observer_can_run", boolScalar(false))
}

func reportsNode(rs []Report) *yaml.Node {
	out := sequence()
	for _, r := range rs {
		out.Content = append(out.Content, reportNode(r))
	}
	return out
}

// anyNode converts decoded YAML/JSON values (agent options) into a node
// with sorted map keys, except that an ATC entry keeps the order osquery's
// documentation uses.
func anyNode(v any) (*yaml.Node, error) {
	switch x := v.(type) {
	case map[string]any:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		if isATCEntry(x) {
			keys = orderKeys(keys, []string{"query", "path", "columns", "platform"})
		} else {
			sort.Strings(keys)
		}
		n := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		for _, k := range keys {
			c, err := anyNode(x[k])
			if err != nil {
				return nil, err
			}
			if k == "columns" {
				c.Style = yaml.FlowStyle
			}
			n.Content = append(n.Content, scalar(k), c)
		}
		return n, nil
	case []any:
		n := sequence()
		for _, e := range x {
			c, err := anyNode(e)
			if err != nil {
				return nil, err
			}
			n.Content = append(n.Content, c)
		}
		return n, nil
	case []string:
		n := sequence()
		for _, e := range x {
			n.Content = append(n.Content, scalar(e))
		}
		return n, nil
	case string:
		return scalar(x), nil
	case bool:
		return boolScalar(x), nil
	case int:
		return intScalar(x), nil
	case int64:
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.FormatInt(x, 10)}, nil
	case float64:
		if x == float64(int64(x)) && x < 1e15 && x > -1e15 {
			return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.FormatInt(int64(x), 10)}, nil
		}
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!float", Value: strconv.FormatFloat(x, 'g', -1, 64)}, nil
	case nil:
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!null", Value: "null"}, nil
	default:
		return nil, fmt.Errorf("unsupported value of type %T", v)
	}
}

func isATCEntry(m map[string]any) bool {
	_, q := m["query"]
	_, p := m["path"]
	_, c := m["columns"]
	return q && p && c
}

// orderKeys puts the preferred keys first, the rest sorted after them.
func orderKeys(keys, first []string) []string {
	have := map[string]bool{}
	for _, k := range keys {
		have[k] = true
	}
	var out []string
	for _, k := range first {
		if have[k] {
			out = append(out, k)
			delete(have, k)
		}
	}
	rest := make([]string, 0, len(have))
	for k := range have {
		rest = append(rest, k)
	}
	sort.Strings(rest)
	return append(out, rest...)
}

// encodeDoc writes a comment header and one YAML document.
func encodeDoc(header string, n *yaml.Node) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	if header != "" {
		b.WriteString("\n")
	}
	e := yaml.NewEncoder(&b)
	e.SetIndent(2)
	if err := e.Encode(n); err != nil {
		return nil, err
	}
	if err := e.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
